#!/usr/bin/env python3
"""Score transcripts.jsonl against PREREG.md's metrics. Pure arithmetic; no model calls."""
import collections, json, math, pathlib, sys
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[2]))
import dissent as D
B = pathlib.Path(__file__).resolve().parent
T = [json.loads(l) for l in open(B / "transcripts.jsonl")]
items = {json.loads(l)["id"]: json.loads(l) for l in open(B / "items.jsonl")}
CLS = ["SUPPORTS", "PARTIAL", "DOES_NOT_SUPPORT"]
def wilson(k, n, z=1.96):
    if n == 0: return "—"
    p = k / n; d = 1 + z*z/n; c = (p + z*z/(2*n)) / d; h = z*math.sqrt(p*(1-p)/n + z*z/(4*n*n)) / d
    return f"{k}/{n} = {100*p:.1f}% [{100*(c-h):.1f}–{100*(c+h):.1f}]"
def norm(v): return v if v in CLS else ("ERROR" if v.startswith("ERROR") else "UNCLEAR")
judges = sorted({t["judge"] for t in T})
by = collections.defaultdict(dict)
for t in T: by[t["id"]][t["judge"]] = t["vote"]
lines = [f"# A-5 results — dissent v0.9.0 L3 on WiCE test (held out)\n",
         f"Transcripts: {len(T)} ({len(by)} items × {len(judges)} judges). Generated by `score.py`.\n"]
for j in judges:
    rows = [(items[i]["gold"], norm(v[j])) for i, v in by.items() if j in v]
    conf = collections.Counter(rows)
    lines.append(f"\n## Judge {j}\n\n| gold \\\\ vote | " + " | ".join(CLS + ["UNCLEAR", "ERROR"]) + " |\n|---|" + "---|" * 5)
    for g in CLS:
        lines.append(f"| {g} | " + " | ".join(str(conf[(g, v)]) for v in CLS + ["UNCLEAR", "ERROR"]) + " |")
    n = len(rows); acc = sum(g == v for g, v in rows)
    f1s = []
    for c in CLS:
        tp = conf[(c, c)]; fp = sum(conf[(g, c)] for g in CLS if g != c); fn = sum(conf[(c, v)] for v in CLS + ["UNCLEAR", "ERROR"] if v != c)
        f1s.append(0 if tp == 0 else 2*tp / (2*tp + fp + fn))
    flag = lambda v: v not in ("SUPPORTS",)
    pos = [(g, v) for g, v in rows if g != "SUPPORTS"]; neg = [(g, v) for g, v in rows if g == "SUPPORTS"]
    tp = sum(flag(v) for g, v in pos); fp = sum(flag(v) for g, v in neg)
    lines += ["",
              f"- 3-class accuracy: {wilson(acc, n)}; macro-F1 {sum(f1s)/3:.3f}",
              f"- **flag recall** (gold ≠ SUPPORTS flagged): {wilson(tp, len(pos))}",
              f"- **flag precision**: {wilson(tp, tp + fp)}",
              f"- **specificity** (gold SUPPORTS not flagged): {wilson(len(neg) - fp, len(neg))}",
              f"- **false accusation** (DOES_NOT_SUPPORT on gold SUPPORTS): {wilson(conf[('SUPPORTS','DOES_NOT_SUPPORT')], len(neg))}",
              f"- **miss** (SUPPORTS on gold DOES_NOT_SUPPORT): {wilson(conf[('DOES_NOT_SUPPORT','SUPPORTS')], sum(1 for g,_ in rows if g=='DOES_NOT_SUPPORT'))}",
              f"- hard flag rather than PARTIAL on gold SUPPORTS∪PARTIAL: {wilson(sum(1 for g,v in rows if g in ('SUPPORTS','PARTIAL') and v=='DOES_NOT_SUPPORT'), sum(1 for g,_ in rows if g in ('SUPPORTS','PARTIAL')))}"]
# combined verdict via dissent's own logic
lines.append("\n## Combined verdict (both judges, dissent v0.9 `Citation.verdict`)\n\n| gold | " +
             " | ".join(["SUPPORTED", "PARTIALLY_SUPPORTED", "UNSUPPORTED", "DISPUTED", "other"]) + " |\n|---|" + "---|" * 5)
comb = collections.Counter()
for i, v in by.items():
    c = D.Citation("t", "u", "q", "c", 1); c.resolved = True; c.verbatim = True; c.support = dict(v)
    ver = c.verdict; ver = ver if ver in ("SUPPORTED", "PARTIALLY_SUPPORTED", "UNSUPPORTED", "DISPUTED") else "other"
    comb[(items[i]["gold"], ver)] += 1
for g in CLS:
    lines.append(f"| {g} | " + " | ".join(str(comb[(g, v)]) for v in ["SUPPORTED", "PARTIALLY_SUPPORTED", "UNSUPPORTED", "DISPUTED", "other"]) + " |")
ns = sum(comb[("SUPPORTS", v)] for v in ["SUPPORTED", "PARTIALLY_SUPPORTED", "UNSUPPORTED", "DISPUTED", "other"])
nn = sum(comb[("DOES_NOT_SUPPORT", v)] for v in ["SUPPORTED", "PARTIALLY_SUPPORTED", "UNSUPPORTED", "DISPUTED", "other"])
lines += ["", f"- UNSUPPORTED (hard flag) on gold SUPPORTS: {wilson(comb[('SUPPORTS','UNSUPPORTED')], ns)}",
          f"- SUPPORTED (clean pass) on gold DOES_NOT_SUPPORT: {wilson(comb[('DOES_NOT_SUPPORT','SUPPORTED')], nn)}",
          f"- DISPUTED overall: {wilson(sum(v for (g,ver),v in comb.items() if ver=='DISPUTED'), len(by))}"]
if len(judges) == 2:
    a, b = judges; pairs = [(norm(v[a]), norm(v[b])) for v in by.values() if a in v and b in v]
    po = sum(x == y for x, y in pairs) / len(pairs)
    ca, cb = collections.Counter(x for x, _ in pairs), collections.Counter(y for _, y in pairs)
    pe = sum(ca[k]*cb[k] for k in set(ca) | set(cb)) / len(pairs)**2
    lines.append(f"- judge agreement: {100*po:.1f}% raw, Cohen's kappa {(po-pe)/(1-pe):.3f} (n={len(pairs)})")
(B / "RESULTS.md").write_text("\n".join(lines) + "\n")
print("\n".join(lines))
